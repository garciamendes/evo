export function dayIsComplete(day: RoadmapDay, completed: Record<string, string>): boolean {
  return day.activities.every((a) => completed[a.id]);
}

/** The first day whose normal activities are not all done. */
export function currentDay(completed: Record<string, string>): RoadmapDay | null {
  return ROADMAP.find((d) => !dayIsComplete(d, completed)) ?? null;
}
