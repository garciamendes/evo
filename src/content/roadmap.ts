type Spec = [title: string, description: string, minutes: number, href?: string];

function activity(day: number, track: Track | "minimo", spec: Spec, minimumTrack?: Track): Activity {
  const [title, description, minutes, href] = spec;
  return {
    id: `d${String(day).padStart(2, "0")}-${track}`,
    track: track === "minimo" ? (minimumTrack ?? "programacao") : track,
    title,
    description,
    minutes,
    href,
  };
}

function day(
  n: number,
  focus: string,
  prog: Spec,
  eng: Spec,
  ai: Spec,
  minimum: [Track, ...Spec],
): RoadmapDay {
  const [minTrack, ...minSpec] = minimum;
  return {
    day: n,
    week: Math.ceil(n / 5),
    focus,
    activities: [activity(n, "programacao", prog), activity(n, "ingles", eng), activity(n, "ia", ai)],
    minimum: activity(n, "minimo", minSpec as Spec, minTrack),
  };
}

